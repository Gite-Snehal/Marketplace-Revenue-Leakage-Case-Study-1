CREATE DATABASE MARKETPLACE_REVENUE_LEAKAGE_PROJECT_CASE_STUDY_1;

CREATE TABLE MARKETPLACE_TRANSACTIONS_REVENUE (
                                                 TRANSACTION_ID VARCHAR,
                                                  ORDER_ID VARCHAR,
                                                  CUSTOMER_ID VARCHAR,
                                                  SELLER_ID VARCHAR,
                                                  PRODUCT_CATEGORY VARCHAR,
                                                  ORDER_TIMESTAMP DATE,
                                                  CUSTOMER_ACQUISITION_DATE DATE,
                                                  ACQUISITION_CHANNEL VARCHAR,
                                                  ORDER_STATUS VARCHAR,
                                                  QUANTITY INTEGER,
                                                  UNIT_LIST_PRICE NUMERIC(12,2),
                                                  UNIT_SELLING_PRICE NUMERIC(12,2),
                                                  DISCOUNT_AMOUNT NUMERIC(12,2),
                                                  REFUND_AMOUNT NUMERIC(12,2),
                                                  PAYMENT_FEE NUMERIC(12,2),
                                                  FULFILMENT_COST NUMERIC(12,2),
                                                  SELLER_COMMISSION_RATE NUMERIC(5,3),
                                                  CUSTOMER_SEGMENT VARCHAR
												  
												 );


-- *) COUNT TOTAL ROWS IN THE TABLE

SELECT COUNT(*) AS TOTAL_ROWS
FROM MARKETPLACE_TRANSACTIONS_REVENUE;

-- *) DATE RANGE: WHAT ARE THE OLDEST AND THE NEWEST DATES IN ORDER_TIMESTAMP?

SELECT MIN(ORDER_TIMESTAMP) AS OLDEST_DATE,
       MAX(ORDER_TIMESTAMP) AS NEWEST_DATE
FROM MARKETPLACE_TRANSACTIONS_REVENUE;

-- *)  FOR ORDER_STATUS, PRODUCT_CATEGORY, ACQUISITION_CHANNEL AND CUSTOMER_SEGMENT,
--    SHOW THE DISTINCT VALUES AND THEIR COUNTS.

SELECT 'ORDER_STATUS' AS COL, ORDER_STATUS AS VALUE, COUNT(*) AS CNT
FROM MARKETPLACE_TRANSACTIONS_REVENUE GROUP BY ORDER_STATUS

UNION ALL

SELECT 'PRODUCT_CATEGORY', PRODUCT_CATEGORY, COUNT(*)
FROM MARKETPLACE_TRANSACTIONS_REVENUE GROUP BY PRODUCT_CATEGORY

UNION ALL

SELECT 'ACQUISITION_CHANNEL', ACQUISITION_CHANNEL, COUNT(*)
FROM MARKETPLACE_TRANSACTIONS_REVENUE GROUP BY ACQUISITION_CHANNEL

UNION ALL

SELECT 'CUSTOMER_SEGMENT', CUSTOMER_SEGMENT, COUNT(*)
FROM MARKETPLACE_TRANSACTIONS_REVENUE GROUP BY CUSTOMER_SEGMENT
ORDER BY COL, CNT DESC;

-- *) DUPLICATE TRANSACTION_ID CHECK

SELECT TRANSACTION_ID, COUNT(*)
FROM MARKETPLACE_TRANSACTIONS_REVENUE
GROUP BY TRANSACTION_ID
HAVING COUNT(*) > 1;

-- *) NULL CHECKS 

SELECT
  COUNT(*) FILTER (WHERE DISCOUNT_AMOUNT IS NULL) AS NULL_DISCOUNT,
  COUNT(*) FILTER (WHERE REFUND_AMOUNT IS NULL)   AS NULL_REFUND,
  COUNT(*) FILTER (WHERE PAYMENT_FEE IS NULL)     AS NULL_FEE,
  COUNT(*) FILTER (WHERE FULFILMENT_COST IS NULL) AS NULL_FULFIL
FROM MARKETPLACE_TRANSACTIONS_REVENUE;

-- *) STATUS WISE REFUND

SELECT ORDER_STATUS, COUNT(*) AS LINES, SUM(REFUND_AMOUNT) AS TOTAL_REFUND
FROM MARKETPLACE_TRANSACTIONS_REVENUE
GROUP BY ORDER_STATUS;


